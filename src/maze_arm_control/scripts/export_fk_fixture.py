#!/usr/bin/env python3
"""Write test/data/fk_fixture.yaml: joint poses and the board pose maze_arm's Python FK gives for each.

The C++ FK in this package is tested against it, so the two stay the same kinematics.
    python3 src/maze_arm_control/scripts/export_fk_fixture.py   # from the repository root
"""

import json
import sys
from pathlib import Path

import numpy as np
import yaml

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "src" / "maze_arm"))
from maze_arm.kinematics import fk_board  # noqa: E402


def main():
    sim = yaml.safe_load((REPO / "src/maze_sim_description/config/sim.yaml").read_text())
    report = json.loads((REPO / "maze_CAD/levels/L1/sim/parts_report.json").read_text())
    grasp = sim["board"]["grasp_offset"]
    handle_center = (np.asarray(report["handle"]["center_mm"], float) / 1000.0).tolist()
    home = np.array(sim["robot"]["initial_joints"], float)
    rng = np.random.default_rng(14)
    qs = [home, np.zeros(6)] + [home + rng.uniform(-1.0, 1.0, 6) for _ in range(20)]
    poses = []
    for q in qs:
        T = fk_board(q, grasp["xyz"], grasp["rpy"], handle_center)
        poses.append({"q": [float(v) for v in q], "T": [float(v) for v in T.reshape(-1)]})
    out = {
        "grasp_xyz": [float(v) for v in grasp["xyz"]],
        "grasp_rpy": [float(v) for v in grasp["rpy"]],
        "handle_center": handle_center,
        "poses": poses,
    }
    path = Path(__file__).resolve().parents[1] / "test" / "data" / "fk_fixture.yaml"
    header = "# Generated by scripts/export_fk_fixture.py from maze_arm.kinematics.fk_board; do not edit.\n"
    path.write_text(header + yaml.safe_dump(out, default_flow_style=None, width=200))
    print(f"wrote {len(poses)} poses to {path}")


if __name__ == "__main__":
    main()
